    async def on_message(self, message: discord.Message) -> None:
        if message.author.bot or message.webhook_id or not self.user:
            return
        channel_id = message.channel.id
        mentioned = self.user in getattr(message, "mentions", ())

        # Passive evidence archive: no model call is made here. Only public guild
        # messages visible to the bot are stored, and interpretations remain deferred.
        guild = getattr(message, "guild", None)
        memory_store = self._get_memory_store()
        raw_content = (message.content or "").strip()
        if memory_store is not None and guild is not None and raw_content:
            try:
                created = getattr(message, "created_at", None)
                stamp = created.timestamp() if created is not None else time.time()
                memory_store.record(
                    message_id=message.id,
                    guild_id=guild.id,
                    channel_id=channel_id,
                    user_id=message.author.id,
                    display_name=(
                        getattr(message.author, "display_name", None)
                        or getattr(message.author, "name", None)
                        or str(message.author.id)
                    ),
                    content=raw_content,
                    created_at=stamp,
                )
                if re.search(r"\b(?:happy\s+(?:birthday|bday)|hbd)\b", raw_content, re.I):
                    targets = [
                        member
                        for member in getattr(message, "mentions", ())
                        if member.id != self.user.id and not getattr(member, "bot", False)
                    ]
                    if len(targets) == 1:
                        memory_store.record_birthday_signal(
                            guild_id=guild.id,
                            subject_user_id=targets[0].id,
                            observer_user_id=message.author.id,
                            message_id=message.id,
                            month=created.month
                            if created is not None
                            else datetime.now(timezone.utc).month,
                            day=created.day
                            if created is not None
                            else datetime.now(timezone.utc).day,
                            created_at=stamp,
                        )
            except (OSError, ValueError, RuntimeError, sqlite3.Error):
                self._memory_store_unavailable = True
                self._memory_store = None
                logger.warning("Long-term Discord memory could not be saved")
        reference = getattr(message, "reference", None)
        resolved = getattr(reference, "resolved", None) if reference else None
        reference_id = getattr(reference, "message_id", None) if reference else None
        reference_channel_id = getattr(reference, "channel_id", None) if reference else None
        if reference_channel_id is None and resolved is not None:
            reference_channel_id = getattr(resolved, "channel_id", None)
            if reference_channel_id is None:
                reference_channel_id = getattr(getattr(resolved, "channel", None), "id", None)
        same_channel_reference = bool(
            (resolved is not None and reference_channel_id == channel_id)
            or (reference is not None and reference_channel_id == channel_id)
        )
        replied_to_bot = bool(
            self.config.enable_message_content
            and same_channel_reference
            and getattr(getattr(resolved, "author", None), "id", None) == self.user.id
        )
        configured_interaction = (
            not self.config.interaction_channel_ids
            or channel_id in self.config.interaction_channel_ids
        )
        reply_all = (
            self.config.enable_message_content
            and channel_id in self.replyall_enabled
            and channel_id in self.config.replyall_channel_ids
        )
        if not reply_all and not (configured_interaction and (mentioned or replied_to_bot)):
            return
        scope = self._scope(message)
        if not self.allowed(scope):
            return
        content = (message.content or "").strip()
        content = re.sub(rf"<@!?{self.user.id}>", "", content).strip()
        intent = parse_request_intent(content)
        image_attachment = next(
            (
                item
                for item in getattr(message, "attachments", ())
                if str(getattr(item, "content_type", "")).lower().startswith("image/")
            ),
            None,
        )
        reference_context = ""
        reference_image_attachment = None
        reference_available = bool(
            same_channel_reference and self._can_read_channel(message.channel, message.author)
        )
        if reference_available and resolved is not None:
            reference_text = serialize_message(resolved)
            if reference_text:
                ref_author = getattr(resolved, "author", None)
                ref_name = (
                    getattr(ref_author, "display_name", None)
                    or getattr(ref_author, "name", None)
                    or "Referenced user"
                )
                reference_context = f"Referenced message from {ref_name}: {reference_text}"
            if image_attachment is None:
                reference_image_attachment = next(
                    (
                        item
                        for item in getattr(resolved, "attachments", ())
                        if str(getattr(item, "content_type", "")).lower().startswith("image/")
                    ),
                    None,
                )
        invocation_image_attachment = image_attachment
        if reference_image_attachment is not None and invocation_image_attachment is None:
            reference_context = (
                reference_context
                or "Referenced message contains an attached image supplied with this request."
            )
        if not content and image_attachment is not None:
            content = "Please describe this image."
        elif not content and (reference_context or same_channel_reference):
            content = "Please respond to the referenced message."
        if len(content) > self.config.max_input_chars:
            await message.channel.send(
                f"That message is too long (maximum {self.config.max_input_chars} characters).",
                allowed_mentions=discord.AllowedMentions.none(),
            )
            return
        if not content:
            return

        if intent.draw_prompt:
            if not self.config.enable_image_generation:
                await message.channel.send(
                    PUBLIC_FAILURE, allowed_mentions=discord.AllowedMentions.none()
                )
                return
            try:
                settings = self.get_settings(scope)
                image = await self.generate_image(
                    intent.draw_prompt, scope, (settings.provider, settings.model)
                )
                embed = discord.Embed(
                    title="Generated image", description=intent.draw_prompt[:1000]
                )
                if isinstance(image, str):
                    embed.set_image(url=image)
                    await message.channel.send(
                        embed=embed,
                        reference=message,
                        mention_author=False,
                        allowed_mentions=discord.AllowedMentions.none(),
                    )
                else:
                    await message.channel.send(
                        file=discord.File(io.BytesIO(image), filename="generated.png"),
                        reference=message,
                        mention_author=False,
                        allowed_mentions=discord.AllowedMentions.none(),
                    )
            except (ProviderError, BudgetError, BotRequestError) as exc:
                await message.channel.send(
                    public_error_message(exc), allowed_mentions=discord.AllowedMentions.none()
                )
            except Exception:
                await message.channel.send(
                    PUBLIC_FAILURE, allowed_mentions=discord.AllowedMentions.none()
                )
            return
        context_count = (
            min(self.config.automatic_context_count, 20)
            if self.config.enable_message_content
            else 0
        )
        if context_count and not self._can_read_channel(message.channel, message.author):
            context_count = 0

        async def load_context() -> str:
            parts: list[str] = []
            request_reference = reference_context
            request_reference_image = reference_image_attachment
            fetch_reference = getattr(message.channel, "fetch_message", None)
            if reference_available and reference_id is not None and callable(fetch_reference):
                # Fetch the exact reply target only after this message has passed
                # gating and entered respond's existing request slot/deadline.
                try:
                    fresh = await fetch_reference(reference_id)
                except (discord.Forbidden, discord.NotFound):
                    fresh = None
                    request_reference = "Referenced message content is unavailable."
                    request_reference_image = None
                except discord.HTTPException:
                    fresh = None  # Keep resolved cached data as a fallback on transient errors.
                if fresh is not None:
                    serialized = serialize_message(fresh)
                    request_reference_image = next(
                        (
                            item
                            for item in getattr(fresh, "attachments", ())
                            if str(getattr(item, "content_type", "")).lower().startswith("image/")
                        ),
                        None,
                    )
                    if serialized:
                        author = getattr(fresh, "author", None)
                        name = (
                            getattr(author, "display_name", None)
                            or getattr(author, "name", None)
                            or "Referenced user"
                        )
                        request_reference = f"Referenced message from {name}: {serialized}"
                    elif (
                        request_reference_image is not None and invocation_image_attachment is None
                    ):
                        request_reference = "Referenced message contains an attached image supplied with this request."
                    else:
                        request_reference = "Referenced message content is unavailable."
            if same_channel_reference and not request_reference:
                request_reference = "Referenced message content is unavailable."
            loaded_reference_image[0] = request_reference_image
            if request_reference:
                parts.append(request_reference)
            if guild is not None:
                relevant_users = {message.author.id}
                relevant_users.update(
                    member.id
                    for member in getattr(message, "mentions", ())
                    if not getattr(member, "bot", False)
                )
                memory_context = self._memory_context(
                    guild.id, content, user_ids=tuple(relevant_users)
                )
                if memory_context:
                    parts.append(memory_context)
            if context_count:
                try:
                    parts.append(
                        await self._channel_context(
                            message.channel, message.author, context_count, before=message
                        )
                    )
                except BotRequestError:
                    parts.append("Recent channel context is unavailable for this request.")
            urls = re.findall(r"https?://[^\s<>\"]+", content)
            if self.config.enable_web_browsing and urls:
                url = urls[0].rstrip(".,!?;:)")
                if len(url) <= 1600:
                    try:
                        source = await self.web_service.browse(url)
                    except WebError:
                        parts.append("The linked page could not be loaded for this request.")
                    else:
                        parts.append(self._format_sources([source]))
                        parts.append(f"Source URL: {source.url}")
            return "\n\n".join(part for part in parts if part)[: self.config.web_max_chars]

        async def load_reference_attachment() -> discord.Attachment | None:
            # load_context fills this inside respond's existing request slot.
            return loaded_reference_image[0] or invocation_image_attachment

        loaded_reference_image = [reference_image_attachment]

        # Public-message context is always its own non-private conversation key.
        try:
            settings = self.get_settings(scope)
            settings_snapshot = (settings.provider, settings.model, settings.persona)
            async with message.channel.typing():
                reply = await self.respond(
                    scope,
                    content,
                    private=False,
                    settings_snapshot=settings_snapshot,
                    attachment=invocation_image_attachment,
                    attachment_loader=load_reference_attachment if reference_available else None,
                    context_loader=load_context
                    if context_count
                    or reference_context
                    or same_channel_reference
                    or self.config.enable_web_browsing
                    else None,
                    speaker_label=(
                        getattr(message.author, "display_name", None)
                        or getattr(message.author, "name", None)
                        or f"User {message.author.id}"
                    ),
                    include_shared_history=self._can_read_shared_history(
                        message.channel, message.author
                    ),
                    reasoning_requested=intent.reasoning_requested,
                )
            from utils.message_utils import send_split_message

            await send_split_message(reply, message, ephemeral=False)
        except (ProviderError, BudgetError) as exc:
            await message.channel.send(
                public_error_message(exc), allowed_mentions=discord.AllowedMentions.none()
            )
        except BotRequestError as exc:
            await message.channel.send(
                public_error_message(exc), allowed_mentions=discord.AllowedMentions.none()
            )
        except (WebError, ValueError) as exc:
            await message.channel.send(
                public_error_message(exc), allowed_mentions=discord.AllowedMentions.none()
            )
        except Exception:
            await message.channel.send(
                "I couldn't complete that request. Please try again later.",
                allowed_mentions=discord.AllowedMentions.none(),
            )
